'use strict';
const assert=require('node:assert/strict');
const {calculate,compare,exitEstimate,ALTERNATIVES,addMonths}=require('./logic.js');
const defaults={price:9170000,unitType:'commercial',deliveryDate:'2026-11-01',paidUSD:5000,historicalFX:50,paidEGP:0,paidFeesEGP:0,spotFX:52,studyFeeUSD:50,extraAnnualPercent:2.5,extraMode:'balance-annual',rates:{},fx:{}};
const pick=(id)=>ALTERNATIVES.find(a=>a.id===id);
assert.equal(addMonths('2026-11-30',3),'2027-02-28');
assert.equal(ALTERNATIVES.filter(x=>x.official).length,6);
const a1=calculate(defaults,pick('a1'));
assert.equal(a1.installments.length,0);
assert.ok(Math.abs(a1.discountEGP-9170000*.07)<.01);
assert.equal(a1.maintenance,9170000*.12);
assert.equal(a1.fees,9170000*.015);
assert.ok(Math.abs(a1.paidPrincipal-250000)<.01);
assert.ok(Math.abs(a1.bookingPrincipal+a1.deliveryPrincipal+250000-a1.gross)<.01);
const a2=calculate(defaults,pick('a2'));
assert.equal(a2.installments.length,4);assert.equal(a2.totalInterest,0);assert.equal(a2.totalSurcharge,0);
const a3=calculate(defaults,pick('a3'));assert.equal(a3.installments.length,12);
const a45=calculate(defaults,pick('a4-5'));assert.equal(a45.installments.length,20);
const a47=calculate(defaults,pick('a4-7'));assert.equal(a47.installments.length,28);
const a410=calculate(defaults,pick('a4-10'));assert.equal(a410.installments.length,40);
assert.equal(a45.installments[0].date,'2027-02-01');
assert.ok(Math.abs(a45.installments.reduce((s,a)=>s+a.principal,0)-a45.principalFinanced)<.02);
assert.ok(Math.abs(a45.installments.at(-1).ending)<.02);
const low=calculate({...defaults,rates:{2027:8,2028:7,2029:6,2030:5,2031:4,2032:3}},pick('a4-5'));
const high=calculate({...defaults,rates:{2027:30,2028:30,2029:30,2030:30,2031:30,2032:30}},pick('a4-5'));
assert.ok(low.totalInterest < a45.totalInterest);
assert.ok(high.totalInterest > a45.totalInterest);
const cheapFx=calculate({...defaults,fx:{2027:90,2028:90,2029:90,2030:90,2031:90,2032:90}},pick('a4-5'));
assert.ok(cheapFx.totalInstallmentsUSD < a45.totalInstallmentsUSD);
assert.ok(Math.abs(cheapFx.totalEGP-a45.totalEGP)<.001);
const c=compare({...defaults,budgetBooking:0,budgetDelivery:0,budgetQuarter:0});assert.ok(c.best && c.best.official);
const tight=compare({...defaults,budgetBooking:1,budgetDelivery:1,budgetQuarter:1});assert.equal(tight.best,null);
const ex=exitEstimate(defaults,'before','2026-10-17');assert.equal(ex.legalPenalty,137550);
assert.equal(ex.refundable,250000-137550);
const exPaid=exitEstimate({...defaults,paidFeesEGP:137550},'before','2026-10-17');assert.equal(exPaid.refundable,250000); // don't deduct already-paid fees twice
const exAfter=exitEstimate({...defaults,actualHandoverDate:'2026-04-17'},'after','2026-10-17');assert.ok(exAfter.occupancy>0);
console.log('All 24+ calculation invariants passed');
